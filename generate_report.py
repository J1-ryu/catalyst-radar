def load_portfolio_config():
    """portfolio_config.py から設定を読み込み、正規化した辞書で返す。

    portfolio_config.py が無い場合、または全項目が空の場合は None を返し、
    呼び出し側はポートフォリオを考慮しない汎用的な分析にフォールバックする。
    個々の項目は任意であり、設定されたものだけが辞書に入る。
    """
    try:
        import portfolio_config as module
    except ImportError:
        return None

    config = {}
    for name, aliases in PORTFOLIO_CONFIG_KEYS.items():
        for alias in aliases:
            value = getattr(module, alias, None)
            if value:
                config[name] = value
                break

    return config or None


